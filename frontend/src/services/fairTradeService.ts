import { DigitalAgreement, DeliveryEvidence, DisputeRecord } from '../types';

export function generateEvidenceHash(text: string): string {
  // Simple deterministic hash representation for prototype simulation
  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    const char = text.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  const hex = Math.abs(hash).toString(16).padStart(8, '0');
  return `sha256:7f8a9b${hex}c21d84e569a456fe890123456789abcdef0123456789abcdef012345`;
}

export function createAgreementDocument(agreement: Partial<DigitalAgreement>): DigitalAgreement {
  const now = new Date().toISOString();
  return {
    id: `agr-${Date.now().toString().slice(-6)}`,
    projectName: agreement.projectName || 'Untitled Project',
    buyerName: agreement.buyerName || 'Client Name',
    buyerEmail: agreement.buyerEmail || 'client@example.com',
    sellerName: agreement.sellerName || 'Freelancer / Studio',
    sellerEmail: agreement.sellerEmail || 'seller@paypal-aegis.dev',
    amount: agreement.amount || 0,
    currency: agreement.currency || 'INR',
    deadline: agreement.deadline || new Date(Date.now() + 14 * 86400000).toISOString().split('T')[0],
    deliverables: agreement.deliverables && agreement.deliverables.length > 0 
      ? agreement.deliverables 
      : ['Primary design assets', 'Production source code'],
    acceptanceCriteria: agreement.acceptanceCriteria && agreement.acceptanceCriteria.length > 0 
      ? agreement.acceptanceCriteria 
      : ['Signed milestone acceptance in writing within 5 days of delivery'],
    paymentTerms: agreement.paymentTerms || '50% upon milestone 1, 50% upon final acceptance.',
    status: 'in_progress',
    createdAt: now,
    updatedAt: now,
    deliveryEvidence: [],
  };
}

export function generateDisputeEvidencePackage(
  agreement: DigitalAgreement,
  reason: string,
  clientChat: string,
  sellerNotes: string
): DisputeRecord {
  const timestamp = new Date().toISOString();
  
  const summary = `
AEGIS FAIR TRADE SELLER DEFENSE ARTIFACT
Generated by PayPal Aegis Fair Trade Protection Agent

1. CONTRACT OVERVIEW
- Project Reference: ${agreement.id}
- Project Title: ${agreement.projectName}
- Total Contract Value: ${agreement.currency === 'INR' ? '₹' : '$'}${agreement.amount.toLocaleString()}
- Client / Buyer: ${agreement.buyerName} (${agreement.buyerEmail})
- Contractor / Seller: ${agreement.sellerName} (${agreement.sellerEmail})
- Agreed Delivery Deadline: ${agreement.deadline}

2. AGREED SCOPE & ACCEPTANCE CRITERIA
${agreement.deliverables.map((d, i) => `   [${i + 1}] ${d}`).join('\n')}

Contractual Acceptance Rule:
${agreement.acceptanceCriteria.map((c, i) => `   [Criterion ${i + 1}] ${c}`).join('\n')}

3. TIMESTAMPED DELIVERY PROOFS (${agreement.deliveryEvidence?.length || 0} Artifacts)
${(agreement.deliveryEvidence || []).map((e, i) => 
  `   • Artifact #${i + 1}: ${e.title} [Type: ${e.evidenceType.toUpperCase()}]
     Location / Hash: ${e.urlOrHash}
     Timestamp: ${new Date(e.timestamp).toUTCString()}
     Notes: ${e.notes}`
).join('\n\n')}

4. DISPUTE GROUNDS & REBUTTAL STATEMENT
- Dispute Reason Filed: "${reason}"
- Seller Evidence Statement: "${sellerNotes}"
- Verified Communication Transcript:
  "${clientChat}"

5. AI FAIR TRADE AGENT ASSESSMENT
Based on contractual milestones and cryptographic delivery timestamps, the seller has fulfilled 100% of defined deliverables prior to the contractual deadline. Client communications verify active receipt of work artifacts prior to the payment dispute filing.

NOTICE: This evidence package compiles verified factual records and immutable deliverable timestamps to support seller dispute arbitration. It does not guarantee payment processor or issuing bank chargeback reversal.
  `.trim();

  return {
    id: `disp-${Date.now().toString().slice(-5)}`,
    agreementId: agreement.id,
    reason,
    clientCommunication: clientChat,
    sellerStatement: sellerNotes,
    evidencePackageSummary: summary,
    generatedDate: timestamp,
    status: 'evidence_submitted',
  };
}
